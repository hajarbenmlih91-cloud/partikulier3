#!/usr/bin/env python3
"""Build and execute the job-local signed n8n workflow; never prints its secret or body."""
import base64
import hashlib
import hmac
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request
import uuid


def build():
    temp = pathlib.Path(os.environ['RUNNER_TEMP'])
    secret = os.environ['PK_EPHEMERAL_SECRET']
    key = base64.b64decode(secret, validate=True)
    wp_ip = os.environ['WP_CONTAINER_IP']
    wp_home = os.environ['WP_HOME']
    listing = json.loads((temp / 'listing.json').read_text())
    run_id = os.environ['GITHUB_RUN_ID']
    attempt = os.environ['GITHUB_RUN_ATTEMPT']
    # Use WordPress's explicit REST route query so the disposable apache
    # instance does not depend on .htaccess being generated by wp_install.
    endpoint = f'http://{wp_ip}/?rest_route=%2Fpartikulier%2Fv1%2Fautomation-event'

    journeys = [listing['deposit'], listing['creation'], listing['login']]
    labels = ['Deposit', 'Creation', 'Connexion existing']
    events = []
    for index, (journey, label) in enumerate(zip(journeys, labels)):
        events.append((f'{label} wrong sender', 'n8n-page-wrong-{index}', {
            'code': journey['code'], 'sender_phone': '212699999999',
            'provider_message_id': f'ci-wrong-{index}-{run_id}',
        }))
    for index, (journey, label) in enumerate(zip(journeys, labels)):
        events.append((f'{label} confirmed inbound', f'n8n-page-match-{index}', {
            'code': journey['code'], 'sender_phone': journey['phone'],
            'provider_message_id': f'ci-match-{index}-{run_id}',
        }))
    nodes = [{'id': str(uuid.uuid4()), 'name': 'Manual Trigger', 'type': 'n8n-nodes-base.manualTrigger', 'typeVersion': 1, 'position': [200, 300], 'parameters': {}}]
    for index, (name, suffix, payload) in enumerate(events):
        event_id = f'{suffix}-{run_id}-{attempt}'
        body = json.dumps({'event_id': event_id, 'event_type': 'whatsapp_inbound', 'source': 'n8n', 'payload': payload}, separators=(',', ':'), ensure_ascii=False)
        timestamp = str(int(time.time()))
        canonical = f'POST\n/partikulier/v1/automation-event\n{timestamp}\n{body}'.encode()
        signature = 'sha256=' + hmac.new(key, canonical, hashlib.sha256).hexdigest()
        headers = [
            {'name': 'Content-Type', 'value': 'application/json'},
            {'name': 'Host', 'value': 'wordpress:8080'},
            {'name': 'X-Partikulier-Automation', 'value': secret},
            {'name': 'X-Partikulier-Algorithm', 'value': 'sha256'},
            {'name': 'X-Partikulier-Timestamp', 'value': timestamp},
            {'name': 'X-Partikulier-Key-Id', 'value': 'N'},
            {'name': 'X-Partikulier-Signature', 'value': signature},
        ]
        params = {
            'method': 'POST', 'url': endpoint, 'sendHeaders': True,
            'headerParameters': {'parameters': headers}, 'sendBody': True,
            'contentType': 'raw', 'rawContentType': 'application/json', 'body': body,
            'options': {'response': {'response': {'fullResponse': True, 'neverError': True, 'responseFormat': 'json'}}},
        }
        nodes.append({'id': str(uuid.uuid4()), 'name': name, 'type': 'n8n-nodes-base.httpRequest', 'typeVersion': 4.2, 'position': [440 + index * 240, 300], 'parameters': params})

    wait_name = 'Keep browser pages open before valid sender'
    nodes.append({'id': str(uuid.uuid4()), 'name': wait_name, 'type': 'n8n-nodes-base.wait', 'typeVersion': 1.1, 'position': [1600, 500], 'parameters': {'amount': 16, 'unit': 'seconds'}})
    connections = {'Manual Trigger': {'main': [[{'node': events[0][0], 'type': 'main', 'index': 0}]]}}
    for index in range(2):
        connections[events[index][0]] = {'main': [[{'node': events[index + 1][0], 'type': 'main', 'index': 0}]]}
    connections[events[2][0]] = {'main': [[{'node': wait_name, 'type': 'main', 'index': 0}]]}
    connections[wait_name] = {'main': [[{'node': events[3][0], 'type': 'main', 'index': 0}]]}
    for index in range(3, len(events) - 1):
        connections[events[index][0]] = {'main': [[{'node': events[index + 1][0], 'type': 'main', 'index': 0}]]}
    workflow_id = str(uuid.uuid4())
    workflow = {'id': workflow_id, 'name': 'Disposable signed WhatsApp journeys to open browser pages', 'active': False, 'nodes': nodes, 'connections': connections, 'settings': {'executionOrder': 'v1'}, 'staticData': None, 'pinData': {}, 'tags': []}
    http_nodes = [node for node in nodes if node['type'] == 'n8n-nodes-base.httpRequest']
    assert len(http_nodes) == 6 and len({node['parameters']['url'] for node in http_nodes}) == 1
    assert all(node['parameters']['url'] == endpoint for node in http_nodes)
    assert all(node['parameters']['body'].find('"event_type":"whatsapp_inbound"') >= 0 for node in http_nodes)
    assert set(node['type'] for node in nodes) == {'n8n-nodes-base.manualTrigger', 'n8n-nodes-base.httpRequest', 'n8n-nodes-base.wait'}
    assert all(node['parameters']['headerParameters']['parameters'][1]['value'] == 'wordpress:8080' for node in http_nodes)
    serialized = json.dumps(workflow).lower()
    assert not any(term in serialized for term in ('graph.facebook.com', 'evolution api', 'whatsapp node', 'meta node', 'wa.me'))
    target = temp / 'whatsapp-n8n-workflow.json'
    target.write_text(json.dumps(workflow, separators=(',', ':'), ensure_ascii=False))
    target.chmod(0o600)
    (temp / 'whatsapp-n8n-workflow-id').write_text(workflow_id)
    (temp / 'whatsapp-n8n-endpoint').write_text(endpoint)
    print(json.dumps({'workflow_nodes': 8, 'http_nodes': 6, 'destination': endpoint}, ensure_ascii=False))


def execute():
    import http.cookiejar
    temp = pathlib.Path(os.environ['RUNNER_TEMP'])
    base = os.environ['N8N_BASE'].rstrip('/')
    password = os.environ['N8N_OWNER_PASSWORD']
    workflow_id = (temp / 'whatsapp-n8n-workflow-id').read_text().strip()
    jar = http.cookiejar.CookieJar()
    client = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(jar))

    def call(method, path, payload=None):
        data = None if payload is None else json.dumps(payload, separators=(',', ':')).encode()
        req = urllib.request.Request(base + path, data=data, method=method, headers={'Content-Type': 'application/json', 'Accept': 'application/json'})
        try:
            with client.open(req, timeout=30) as res:
                raw = res.read().decode('utf-8', 'replace')
                return res.status, json.loads(raw) if raw else {}
        except urllib.error.HTTPError as exc:
            raw = exc.read().decode('utf-8', 'replace')
            try: body = json.loads(raw)
            except Exception: body = {}
            return exc.code, body

    def unflatten(value):
        # n8n uses the Flatted JSON representation for execution payloads: a
        # string table whose first entries contain JSON objects and whose
        # numeric strings reference other table entries.
        if not isinstance(value, list) or not value:
            return value
        first = value[0]
        if not isinstance(first, (dict, list)) and not (isinstance(first, str) and first[:1] in ('{', '[')):
            return value
        cache = {}
        def dereference(index, active):
            if index in cache: return cache[index]
            if index in active or index < 0 or index >= len(value): return None
            raw = value[index]
            try: decoded = json.loads(raw) if isinstance(raw, str) and raw[:1] in ('{', '[') else raw
            except Exception: decoded = raw
            result = expand(decoded, active | {index})
            cache[index] = result
            return result
        def expand(item, active):
            if isinstance(item, dict): return {key: expand(child, active) for key, child in item.items()}
            if isinstance(item, list): return [expand(child, active) for child in item]
            if isinstance(item, str) and item.isdigit() and int(item) < len(value):
                return dereference(int(item), active)
            return item
        return dereference(0, set())

    def find(value, key):
        if isinstance(value, dict):
            if key in value: return value[key]
            for child in value.values():
                found = find(child, key)
                if found is not None: return found
        elif isinstance(value, list):
            for child in value:
                found = find(child, key)
                if found is not None: return found
        elif isinstance(value, str) and value.lstrip()[:1] in ('{', '['):
            try: return find(unflatten(json.loads(value)), key)
            except Exception: return None
        return None

    def response_for(run_data, node_name):
        for run in run_data.get(node_name, []) if isinstance(run_data.get(node_name), list) else []:
            groups = run.get('data', {}).get('main', []) if isinstance(run, dict) else []
            for group in groups if isinstance(groups, list) else []:
                for entry in group if isinstance(group, list) else []:
                    value = entry.get('json', {}) if isinstance(entry, dict) else {}
                    if not isinstance(value, dict): continue
                    status = value.get('statusCode', value.get('status', 0))
                    body = value.get('body', value)
                    if isinstance(body, str):
                        try: body = json.loads(body)
                        except Exception: body = {}
                    if isinstance(body, dict):
                        code = body.get('code', '')
                        if not isinstance(code, str) or not re.fullmatch(r'[a-z0-9_]{1,64}', code): code = ''
                        headers = value.get('headers', {})
                        content_type = headers.get('content-type', '') if isinstance(headers, dict) else ''
                        message = body.get('message', '')
                        message = message.lower() if isinstance(message, str) else ''
                        message_kind = next((label for token, label in [('critical error', 'php_critical_error'), ('undefined function', 'missing_function'), ('member function', 'null_method_call'), ('duplicate', 'duplicate_handling'), ('sql', 'database_error'), ('database', 'database_error'), ('permission', 'permission_error'), ('invalid', 'invalid_request')] if token in message), 'other')
                        return {'http': int(status or 0), 'accepted': body.get('accepted'), 'duplicate': body.get('duplicate'), 'processing': body.get('processing'), 'code': code, 'message_kind': message_kind, 'body_keys': sorted(body.keys())[:8], 'json': 'json' in str(content_type).lower()}
        return None

    try:
        owner_code, _ = call('POST', '/rest/owner/setup', {'email': 'ci-owner@example.invalid', 'firstName': 'Disposable', 'lastName': 'CI', 'password': password})
        if owner_code not in (200, 201): raise RuntimeError('owner setup failed')
        login_code, _ = call('POST', '/rest/login', {'emailOrLdapLoginId': 'ci-owner@example.invalid', 'password': password})
        if login_code != 200: raise RuntimeError('owner login failed')
        started_code, started = call('POST', f'/rest/workflows/{workflow_id}/run', {'triggerToStartFrom': {'name': 'Manual Trigger'}})
        if started_code != 200: raise RuntimeError(f'manual run start HTTP {started_code}')
        execution_id = find(started, 'executionId')
        if not execution_id: raise RuntimeError('execution id missing')
        execution = {}
        for _ in range(120):
            status_code, execution = call('GET', f'/rest/executions/{execution_id}?includeData=true')
            if status_code == 200:
                finished = find(execution, 'finished')
                state = find(execution, 'status')
                polled_result = find(execution, 'resultData') or {}
                err = polled_result.get('error') if isinstance(polled_result, dict) else None
                if finished is True or state in ('success', 'error', 'crashed', 'canceled') or err is not None: break
            time.sleep(1)
        else: raise RuntimeError('execution timeout')
        result_data = find(execution, 'resultData') or {}
        # Only the top-level execution error means n8n itself failed. A
        # recursive search also mistakes a WordPress response body's `error`
        # field for an n8n engine failure (notably on an expected HTTP error).
        execution_error = result_data.get('error') if isinstance(result_data, dict) else None
        if execution_error is not None:
            def collect_strings(value, path='', depth=0):
                found = []
                if depth > 4: return found
                if isinstance(value, dict):
                    for key, child in list(value.items())[:40]:
                        found.extend(collect_strings(child, f'{path}.{key}' if path else key, depth + 1))
                elif isinstance(value, list):
                    for child in value[:8]: found.extend(collect_strings(child, path, depth + 1))
                elif isinstance(value, str): found.append((path, value[:500]))
                return found
            safe_class = 'other'
            for path, text in collect_strings(execution_error):
                for token, label in [('pk_automation_auth', 'shared_secret_rejected'), ('pk_automation_signature', 'signature_rejected'), ('pk_automation_payload', 'payload_rejected'), ('ECONNREFUSED', 'connection_refused'), ('ENOTFOUND', 'dns_failure'), ('ETIMEDOUT', 'connection_timeout'), ('401', 'http_401'), ('403', 'http_403'), ('404', 'http_404'), ('429', 'http_429'), ('500', 'http_500'), ('signature', 'signature_rejected'), ('timestamp', 'timestamp_rejected'), ('duplicate', 'duplicate_handling'), ('sql', 'database_error'), ('database', 'database_error'), ('table', 'database_error'), ('connect', 'connection_error'), ('timeout', 'timeout'), ('json', 'json_error')]:

                    if token.lower() in text.lower(): safe_class = label; break
                if safe_class != 'other': break
            node = execution_error.get('node') if isinstance(execution_error, dict) else None
            node_name = node.get('name') if isinstance(node, dict) else (result_data.get('lastNodeExecuted') if isinstance(result_data, dict) else None)
            if node_name not in ('Deposit wrong sender', 'Creation wrong sender', 'Connexion existing wrong sender', 'Deposit confirmed inbound', 'Creation confirmed inbound', 'Connexion existing confirmed inbound', 'Keep browser pages open before valid sender'):
                node_name = 'unknown'
            http_code = execution_error.get('httpCode') if isinstance(execution_error, dict) else None
            http_code = str(http_code) if isinstance(http_code, (str, int)) and re.fullmatch(r'[A-Z0-9_]{2,30}', str(http_code)) else 'none'
            error_name = execution_error.get('name') if isinstance(execution_error, dict) else None
            if not isinstance(error_name, str) or not re.fullmatch(r'[A-Za-z0-9_]{1,40}', error_name): error_name = 'unknown'
            error_type = execution_error.get('type') if isinstance(execution_error, dict) else None
            if not isinstance(error_type, str) or not re.fullmatch(r'[A-Za-z0-9_]{1,40}', error_type): error_type = 'unknown'
            node_keys = sorted(node.keys())[:12] if isinstance(node, dict) else []
            error_keys = sorted(execution_error.keys())[:12] if isinstance(execution_error, dict) else []
            raise RuntimeError(f'n8n execution failed at {node_name}; safe error class={safe_class}; HTTP={http_code}; type={error_type}; error name={error_name}; keys={error_keys}')
        run_data = result_data.get('runData') if isinstance(result_data, dict) else None
        if not isinstance(run_data, dict):
            data_value = execution.get('data') if isinstance(execution, dict) else None
            try:
                decoded_data = json.loads(data_value) if isinstance(data_value, str) else data_value
            except Exception:
                decoded_data = None
            result_value = decoded_data.get('resultData') if isinstance(decoded_data, dict) else None
            record_payload = decoded_data.get('data') if isinstance(decoded_data, dict) else None
            try:
                parsed_payload = json.loads(record_payload) if isinstance(record_payload, str) else record_payload
            except Exception:
                parsed_payload = None
            safe_shape = {
                'payload_type': type(record_payload).__name__,
                'payload_keys': sorted(parsed_payload.keys())[:3] if isinstance(parsed_payload, dict) else [],
                'payload_list_length': len(parsed_payload) if isinstance(parsed_payload, list) else 0,
                'payload_string_lead': record_payload[:1] if isinstance(record_payload, str) else '',
            }
            raise RuntimeError('n8n data missing; payload=' + json.dumps(safe_shape, separators=(',', ':')))
        names = ['Deposit wrong sender', 'Creation wrong sender', 'Connexion existing wrong sender', 'Deposit confirmed inbound', 'Creation confirmed inbound', 'Connexion existing confirmed inbound']
        outcomes = {name: response_for(run_data, name) for name in names}
        if any(value is None for value in outcomes.values()): raise RuntimeError('one or more WordPress request results are missing')
        expected = [(200, True, False, 'disabled')] * 6
        for (name, value), want in zip(outcomes.items(), expected):
            actual = (value['http'], value['accepted'], value['duplicate'], value['processing'])
            if actual != want: raise RuntimeError(f'unexpected WordPress result for {name}: HTTP {value["http"]}; safe code={value["code"] or "none"}; message kind={value["message_kind"]}; JSON={value["json"]}; keys={value["body_keys"]}')
        output = {'responses': {name: {'http': value['http'], 'accepted': value['accepted'], 'duplicate': value['duplicate'], 'processing': value['processing']} for name, value in outcomes.items()}}
        (temp / 'n8n-results.json').write_text(json.dumps(output, separators=(',', ':')))
        print(json.dumps(output, separators=(',', ':')))
    except Exception as exc:
        # Intentionally suppress raw n8n responses, headers, execution data, and bodies.
        print(f'n8n integration failed: {str(exc)[:180]}', file=sys.stderr)
        raise SystemExit(1)


if __name__ == '__main__':
    if len(sys.argv) != 2 or sys.argv[1] not in ('build', 'execute'):
        raise SystemExit('usage: ephemeral-whatsapp-n8n.py build|execute')
    {'build': build, 'execute': execute}[sys.argv[1]]()
